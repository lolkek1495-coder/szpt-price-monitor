"""Создаёт test_prices.csv — ТЕСТОВЫЕ данные: 8 недель цен + специально добавленные
ошибки, дубликаты и аномалии, чтобы было что показать на демо.
Запуск:  python make_test_data.py
"""
import csv
import random
from datetime import date, timedelta

from app import OUTLETS

random.seed(7)

# товар: (базовая цена за кг/л/шт, варианты упаковки [(надпись, количество в базовой единице)])
GOODS = {
    "Хлеб пшеничный": (330, [("600 г", 0.6), ("500 г", 0.5)]),
    "Мука пшеничная 1 сорт": (260, [("2 кг", 2), ("1 кг", 1), ("5 кг", 5)]),
    "Рис шлифованный": (520, [("900 г", 0.9), ("1 кг", 1)]),
    "Гречка": (480, [("800 г", 0.8), ("900 г", 0.9), ("1 кг", 1)]),
    "Макароны": (450, [("400 г", 0.4), ("450 г", 0.45), ("1 кг", 1)]),
    "Сахар": (500, [("900 г", 0.9), ("1 кг", 1), ("5 кг", 5)]),
    "Соль": (90, [("1 кг", 1)]),
    "Картофель": (190, [("1 кг", 1)]),
    "Лук репчатый": (150, [("1 кг", 1)]),
    "Говядина": (3400, [("1 кг", 1), ("500 г", 0.5)]),
    "Молоко 2,5%": (460, [("1 л", 1), ("900 мл", 0.9), ("0,5 л", 0.5)]),
    "Масло подсолнечное": (850, [("1 л", 1), ("0,9 л", 0.9), ("5 л", 5)]),
    "Яйцо куриное С1": (55, [("дес", 10), ("30 шт", 30)]),
}
WEEKS = 8
LAST_DAY = date(2026, 11, 9)
dates = [LAST_DAY - timedelta(weeks=WEEKS - 1 - i) for i in range(WEEKS)]

rows = []
for (outlet, kind, district) in OUTLETS:
    level = (0.95 if kind == "рынок" else 1.0) * random.uniform(0.97, 1.03)
    for product, (base, packs) in GOODS.items():
        label, qty = random.choice(packs)          # у точки своя фасовка
        for i, d in enumerate(dates):
            unit_price = base * level * (1 + 0.004 * i) * random.uniform(0.98, 1.02)
            # аномалия 1: сахар резко дорожает в одной точке на последней неделе
            if product == "Сахар" and outlet == "Супермаркет «Арай»" and i == WEEKS - 1:
                unit_price *= 1.35
            # аномалия 2: гречка дорожает во всём районе Тасбогет за последнюю неделю
            if product == "Гречка" and district == "Тасбогет" and i == WEEKS - 1:
                unit_price *= 1.14
            rows.append([d.isoformat(), outlet, product, round(unit_price * qty / 5) * 5, label])

d = LAST_DAY.isoformat()
# аномалия 3: ошибка в упаковке (50 г вместо 500 г) — неправдоподобная цена за кг
rows = [r for r in rows if not (r[0] == d and r[1] == "Магазин «Самал»" and r[2] == "Хлеб пшеничный")]
rows.append([d, "Магазин «Самал»", "Хлеб пшеничный", 170, "50 г"])
# ошибки ввода и дубликаты
rows += [
    [d, "Магазин «Береке»", "Сахар", 0, "1 кг"],                 # нулевая цена
    [d, "Магазин «Достык»", "Колбаса варёная", 2100, "1 кг"],    # товара нет в справочнике
    [d, "Магазин «Жібек»", "Молоко 2,5%", 480, "1 кг"],          # молоко в кг вместо литров
    [d, "Ларёк у дома", "Соль", 95, "1 кг"],                     # неизвестная точка
    ["09/11/26", "Магазин «Самал»", "Соль", 95, "1 кг"],         # неправильная дата
    [d, "Рынок «Титова»", "Рис шлифованный", 510, "уп"],         # непонятная упаковка
    rows[5][:], rows[40][:],                                     # два дубликата
]

with open("test_prices.csv", "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f, delimiter=";")
    w.writerow(["date", "outlet", "product", "price", "pack"])
    w.writerows(rows)
print(f"Готово: test_prices.csv, строк: {len(rows)}")
